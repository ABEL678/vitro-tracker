# ---------------------------------------------------------------------------
#  Рабочие субботы (отработки праздников)
# ---------------------------------------------------------------------------
WORKING_SATURDAYS = {
    (2024, 4, 27),
    (2024, 11, 2),
    (2024, 12, 28),
}


# ---------------------------------------------------------------------------
#  Публичные функции
# ---------------------------------------------------------------------------
def is_workday(d: date) -> bool:
    """
    Является ли дата рабочим днём по пятидневной неделе РФ.
    Учитывает: пн–пт, кроме праздников, плюс рабочие субботы.
    """
    iso = (d.year, d.month, d.day)

    # Рабочие субботы (объявлены Правительством)
    if iso in WORKING_SATURDAYS:
        return True

    # Выходные (сб, вс)
    if d.weekday() >= 5:  # 5 = суббота, 6 = воскресенье
        return False

    # Праздники
    holidays = HOLIDAYS.get(d.year, set())
    return iso not in holidays


def add_workdays(start: date, n: int) -> date:
    """
    Прибавляет N рабочих дней к дате (отсчёт со следующего дня).
    Если start — рабочий день, отсчёт начинается со следующего дня.
    Если start — выходной, отсчёт начинается с первого рабочего после него.
    """
    if n <= 0:
        return start

    d = start
    added = 0
    while added < n:
        d += timedelta(days=1)
        if is_workday(d):
            added += 1
    return d


def workdays_between(start: date, end: date) -> int:
    """
    Количество рабочих дней между двумя датами (не включая start).
    Если end < start — возвращает 0.
    """
    if end <= start:
        return 0
    d = start
    count = 0
    while d < end:
        d += timedelta(days=1)
        if is_workday(d):
            count += 1
    return count


def parse_date(s: str) -> date | None:
    """
    Парсит дату из строки ISO-формата (2026-09-25T16:50:24Z или 2026-09-25).
    Возвращает None, если не удалось.
    """
    if not s or not isinstance(s, str):
        return None
    s = s.strip().rstrip("Z")
    try:
        # Попробуем ISO с временем
        return date.fromisoformat(s[:10])
    except (ValueError, TypeError):
        return None
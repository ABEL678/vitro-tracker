# vitro/sheets.py
"""
Единый стандарт подсчёта листов РД во всём приложении (PATCH-11).

Проблема: таблица documents содержит по одной строке на каждый ФАЙЛ,
выгруженный из Витро. Повторные выгрузки и ревизии одного и того же
листа дают несколько строк, поэтому вкладки считали «файлы», а не
«листы»: «Сводка по проекту» показывала 52 листа там, где «План выдачи»
(уже после патча 10) — 44 уникальных листа.

ЕДИНЫЙ СТАНДАРТ (с патча 11): один уникальный лист = одна строка.

  1. Ключ уникальности: (complex, sheet_number), если sheet_number
     заполнен (тот же ключ, что в «Плане выдачи» с патча 10).
  2. Строки с ПУСТЫМ sheet_number — самостоятельные листы (fallback
     по id): один файл = один лист, комплект не может «исчезнуть».
     В том числе АННУЛИРОВАННЫЕ строки без номера — каждая считается
     по своему id (патч 12), аннулированные листы не теряются.
  3. Из нескольких ревизий листа остаётся ПОСЛЕДНЯЯ: MAX(status_date),
     при равенстве дат — MAX(id) (последняя выгрузка при синке).
  4. АННУЛИРОВАНИЕ — «ЛИПКОЕ» (патч 12): если ХОТЯ БЫ ОДНА ревизия
     листа имеет статус «Аннулировано», лист учитывается как
     аннулированный — даже если ПОСЛЕДНЯЯ ревизия живая (A/B/C).
     Иначе аннулированная ревизия проигрывала бы последнюю живую
     ревизию по дате/id, и счётчик «Аннулировано» в Сводке падал
     в ноль (было 0 вместо 9).
  5. Замечания (comments) НЕ дедуплицируются: каждое замечание —
     отдельная сущность со своим ID. Дедупликация применяется только
     к подсчёту ЛИСТОВ; замечание, привязанное к старой ревизии,
     продолжает учитываться.
  6. ШИФР КОМПЛЕКТА НОРМАЛИЗУЕТСЯ (патч 13): trim + верхний регистр +
     латинские двойники → кириллица. Синк пишет complex как есть
     (из имён папок SharePoint), поэтому один комплект мог храниться
     под несколькими написаниями («АТ-РД-ОВ2-C-00» латиницей и
     «АТ-РД-ОВ2-С-00» кириллицей, хвостовой пробел) — группировка
     делила его листы: СМИК показывал 33 вместо 44, а фантомные
     варианты раздували «Комплектов всего». После нормализации
     варианты склеиваются и в Сводке, и в Плане выдачи.

Инструменты модуля:
  * sheet_key(row)          — ключ уникальности листа для строки.
  * dedup_document_rows(rows) — список dict'ов → уникальные листы.
  * dedup_documents(df)     — pandas DataFrame → уникальные листы.
  * is_valid_kit_code(code) — True, если строка похожа на шифр
    комплекта (раньше жила в plan_xlsx, патч 13); с патча 19
    понимает 6-й блок без точки и дробные шифры вида
    «…/10511.25.01-ООС1».
  * looks_like_rd_code(name) — светлая проверка «похоже на РД-код»
    для имён папок/файлов Витро любой организации (патч 19):
    замена startswith("АТ-РД-") в sharepoint.py.
  * unique_vitro_sheets(rows) — ЕДИНЫЙ СТАНДАРТ «Плана выдачи»:
    дедуп + отсечение мусорных шифров. Эту функцию вызывают ВСЕ
    вкладки (Сводка, Динамика, Экспорт, Управление), поэтому
    «Листов всего» везде совпадает с «Листов в Витро».
  * sql_count_sheets(alias) — SQL-выражение COUNT(DISTINCT ...) для
    подсчёта уникальных листов прямо в SQL-запросе.
  * normalize_kit_code(code) — каноническая форма шифра комплекта;
    публичная обёртка _norm_complex (патч 21).
  * get_kit_status(complex_code) — статус комплекта «A» / «B» / «C» /
    «План (не загружен)» по последним ревизиям его листов из БД
    (патч 21, подвкладка «Обновить статусы» вкладки «Экспорт»).
  * get_kit_statuses(codes) — батчевый вариант get_kit_status: один
    проход по БД на весь список шифров, codes=None → все комплекты
    базы (патч 21).

Изменения структуры базы НЕ требуются: дедупликация выполняется на
уровне SQL-выражений и pandas; таблицы/представления не создаются.

ПАТЧ 21 — статус комплекта для внешних перечней (Экспорт):
функции get_kit_status / get_kit_statuses сводят статусы УНИКАЛЬНЫХ
листов комплекта (тот же unique_vitro_sheets, что во вкладках) к
одному значению: «A» / «B» / «C» / «План (не загружен)».
"""

import re

# ---------------------------------------------------------------------------
#  Нормализация значений
# ---------------------------------------------------------------------------
# Латинские двойники кириллицы (появляются при копировании шифров
# из CAD/Word и в именах папок SharePoint). Тот же набор, что в
# plan_xlsx._HOMOGLYPHS; дублируется намеренно: sheets.py — базовый
# модуль (его импортирует sqlite_db), тянуть туда plan_xlsx со
# Streamlit нельзя.
_LAT2CYR = str.maketrans({
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К",
    "M": "М", "O": "О", "P": "Р", "T": "Т", "X": "Х",
})


def _norm_complex(v) -> str:
    """Нормализация шифра комплекта (патч 13): строка, trim (включая
    неразрывный пробел \xa0), верхний регистр, латинские двойники →
    кириллица. None/NaN → ''."""
    s = _s(v)
    if not s:
        return ""
    return s.upper().translate(_LAT2CYR)


def _s(v) -> str:
    """None/NaN → '', остальное → str без пробелов по краям."""
    if v is None:
        return ""
    try:
        import pandas as pd
        if pd.isna(v):
            return ""
    except (TypeError, ValueError):
        pass
    return str(v).strip()


def _int(v) -> int:
    """Безопасный int (None/мусор → 0)."""
    try:
        return int(v)
    except (TypeError, ValueError):
        return 0


# ---------------------------------------------------------------------------
#  Валидность шифра комплекта (патч 13; расширены патчами 18 и 19)
# ---------------------------------------------------------------------------
# Шифр комплекта вида АТ-РД-КЖ1-С-00: блоки из заглавных букв/цифр,
# 1–3 блока хвоста. Патч 18 — по реальным комплектам Витро:
#   * в марке (3-й блок) точки допустимы: «ЛВС.АИС», «КЖ2.1», «АР12.1»;
#   * в блоках хвоста (блок и индекс) точки ТОЖЕ допустимы: индексы
#     вида «02.1» («АТ-РД-КМ2-1-02.1»), буква в конце
#     («АТ-РД-АР3-1-08Т»);
#   * ЗАПЯТЫЕ запрещены: «АТ-РД-КЖ1,2-С-П2.3.ВР» — объединение ДВУХ
#     комплектов в одной строке, комплектом не является;
#   * строка не может кончаться точкой или дефисом.
# Патч 19 — 6-й блок и дробные шифры (по папкам ГИС в Витро и
# ведомости АТ-РД-СП-0-00.xlsx; правило согласовано):
#   * 6-й блок БЕЗ ТОЧКИ допустим: приложения-комплекты
#     «АТ-РД-АР1-С-00-СО», «АТ-РД-КЖ1-1-00-ВР» и комплекты ГИС
#     «ГИС-РД-СБ-ООС-С-00». Полный шифр листа по-прежнему НЕ
#     проходит: в 6-м блоке листа всегда есть точка
#     («АТ-РД-АР1-С-00-1.1», «АТ-РД-ОВ1-С-00-10.01»);
#   * дробная ветка: «ГИС-РД-СБ-ООС-С-00/10511.25.01-ООС1» — до «/»
#     обычный комплект (4–6 блоков), после «/» числовая ссылка:
#     цифры и точки суммарно НЕ длиннее 20 символов, после неё
#     максимум ДВА суффикса из букв/цифр (точки в суффиксах
#     запрещены — иначе через хвост проходил бы полный шифр листа
#     «…-ООС1-1.1»);
#   * 7 и больше блоков без «/» — как и раньше, отказ (шифр листа
#     комплекта с 6-блочной базой: «ГИС-РД-СБ-ООС-С-00-1.1»).
# Мусор из папок SharePoint (имена-разделы, «ИТОГО», даты, отдельные
# приложения «СО», «ВР», «П.01») по-прежнему под шаблон не подпадает.
# Раньше шаблон жил в plan_xlsx; перенесён сюда (патч 14), чтобы
# sheets.py оставался единственной точкой правды о шифрах: ОДНА
# функция обслуживает и парсеры Excel (plan_xlsx), и листы из Витро
# (unique_vitro_sheets и фильтры вкладок) — правки патчей 18 и 19
# сделаны в одном месте и действуют на оба источника.
_KIT_CODE_PATTERN = re.compile(
    r"^[A-ZА-ЯЁ]{2,4}-[A-ZА-ЯЁ]{1,3}-[A-ZА-ЯЁ0-9.]+"
    r"(?:-[A-ZА-ЯЁ0-9.]{1,12}){1,2}"
    r"(?:-[A-ZА-ЯЁ0-9]{1,4})?$"
)

# Дробный хвост после «/» (патч 19): числовая ссылка из цифр и точек
# (1–20 символов, начинается с цифры) максимум с ДВУМЯ суффиксами из
# букв/цифр по 1–12 символов.
_FRACTIONAL_TAIL_PATTERN = re.compile(
    r"^\d[\d.]{0,19}(?:-[A-ZА-ЯЁ0-9]{1,12}){0,2}$"
)

# Светлая проверка «похоже на РД-код» (патч 19) — для имён папок и
# файлов из Витро ЛЮБОЙ организации («АТ-РД-…», «ГИС-РД-…»,
# <ОРГ>-РД-…). Проверяется только форма «головы»: 2–4 заглавные
# буквы организации, «-РД-» и минимум два блока после (марка и
# блок); в хвостовых блоках допустимы буквы, цифры, точки и «/»
# (дробные шифры проходят). Хвост после шифра (расширение «.PDF»,
# пометки) не мешает — как раньше делал startswith("АТ-РД-").
# НЕ заменяет is_valid_kit_code: полная валидация комплекта —
# на склейке с Excel (unique_vitro_sheets, plan_xlsx._kit_code_of).
_RD_SHAPE_PATTERN = re.compile(
    r"^[A-ZА-ЯЁ]{2,4}-РД-[A-ZА-ЯЁ0-9.]{1,12}"
    r"(?:-[A-ZА-ЯЁ0-9./]{1,24}){1,}"
)


def is_valid_kit_code(code: str) -> bool:
    """True, если строка похожа на шифр комплекта (АТ-РД-КЖ1-1-00).

    Публичная точка проверки для фильтрации мусорных шифров (патч 13):
    фильтр применяется и к комплектам из ведомостей, и к комплектам
    из Витро (в т. ч. исторический мусор в plan_kits — шифры
    с запятыми/точками вида «АТ-РД-КЖ1,2-С-П2.3.ВР»). Проверяет
    и дробные шифры — обе части до и после «/».

    Патч 18: пропускает реальные комплекты, которые раньше терялись —
    «АТ-РД-ЛВС.АИС-С-00» (точка в марке), «АТ-РД-КМ2-1-02.1» (точка
    и цифра в индексе), «АТ-РД-АР3-1-08Т» (буква в конце); запятая
    в любом месте — гарантированный отказ (объединение двух
    комплектов в одной строке).

    Патч 19: пропускает комплекты с 6-м блоком без точки
    («АТ-РД-АР1-С-00-СО», «ГИС-РД-СБ-ООС-С-00») и дробные шифры
    вида «ГИС-РД-СБ-ООС-С-00/10511.25.01-ООС1» (числовая часть
    до 20 цифр/точек, суффиксов не больше двух). Полные шифры
    листов по-прежнему НЕ проходят: «АТ-РД-АР1-С-00-1.1» (точка
    в 6-м блоке), «ГИС-РД-СБ-ООС-С-00-1.1» (7 блоков),
    «…/10511.25.01-ООС1-1.1» (точка в суффиксе хвоста).
    """
    if not code:
        return False
    s = str(code)
    if "," in s:
        # «АТ-РД-КЖ1,2-С-П2.3.ВР» — объединение двух комплектов
        # в одной строке; регулярка его и так отсекает, явная
        # проверка — для читаемости и на случай будущих правок.
        return False
    if s.endswith(("-", ".")):
        return False
    if "/" in s:
        # Дробный шифр (патч 19): основная часть до «/» — обычный
        # комплект (4–6 блоков), хвост — числовая ссылка с суффиксами
        # (_FRACTIONAL_TAIL_PATTERN).
        base, _, tail = s.partition("/")
        if "/" in tail:
            # второй слэш — не наш формат
            return False
        if base.endswith(("-", ".")) or tail.endswith(("-", ".")):
            return False
        return bool(_KIT_CODE_PATTERN.match(base)
                    and _FRACTIONAL_TAIL_PATTERN.match(tail))
    return bool(_KIT_CODE_PATTERN.match(s))


def looks_like_rd_code(name: str) -> bool:
    """True, если имя похоже на РД-код организации АТ или ГИС (патч 20)."""
    if not name:
        return False
    # Нормализация латиницы в кириллицу (A->А, T->Т, P->Р и т.д.)
    s = str(name).strip().upper().translate(_LAT2CYR)
    # Жесткий список разрешенных организаций
    if not (s.startswith("АТ-РД-") or s.startswith("ГИС-РД-")):
        return False
    # Проверка, что после префикса есть минимум два блока (марка и блок)
    parts = s.split("-")
    if len(parts) < 4:
        return False
    return True


# ---------------------------------------------------------------------------
#  Единый стандарт «Плана выдачи»: уникальные листы в Витро
# ---------------------------------------------------------------------------
def unique_vitro_sheets(rows) -> list:
    """Строки documents (dict) → уникальные листы КОМПЛЕКТОВ В ВИТРО.

    Единый стандарт «Плана выдачи» (патч 14) — ровно то, что раньше
    делал только план.py в _vitro_sheet_counts:
      1) дедупликация dedup_document_rows: последняя ревизия листа
         (ключ complex + sheet_number), «липкое» аннулирование,
         нормализация шифра (trim, регистр, латинские двойники);
      2) остаются только листы комплектов с ВАЛИДНЫМ шифром
         (is_valid_kit_code) — мусорные шифры из папок SharePoint
         исключаются, как в таблице «Плана выдачи».

    Все вкладки (Сводка, Динамика, Экспорт, Управление) считают
    «Листов всего» этой функцией, поэтому цифры совпадают везде
    (расхождение 12 451 vs 11 312 устранено).
    """
    kept = dedup_document_rows(rows)
    return [r for r in kept
            if r.get("complex")
            and is_valid_kit_code(str(r["complex"]))]


# ---------------------------------------------------------------------------
#  Ключ уникальности листа
# ---------------------------------------------------------------------------
def sheet_key(row: dict) -> tuple:
    """
    Ключ уникальности листа для строки documents (dict).

    sheet_number заполнен → ('sheet', complex, sheet_number);
    sheet_number пустой   → ('row', id) — файл сам себе лист (fallback).

    Патч 13: complex нормализуется (_norm_complex) — варианты написания
    шифра (латиница, пробелы) дают ОДИН ключ, листы комплекта
    не делятся между фантомными написаниями.
    """
    sn = _s(row.get("sheet_number"))
    if not sn:
        return ("row", _int(row.get("id")))
    return ("sheet", _norm_complex(row.get("complex")), sn)


def _rev_order(row: dict) -> tuple:
    """Порядок ревизии: чем позже status_date / больше id, тем новее."""
    return (_s(row.get("status_date")), _int(row.get("id")))


# ---------------------------------------------------------------------------
#  Дедупликация
# ---------------------------------------------------------------------------
def dedup_document_rows(rows) -> list:
    """
    Список строк documents (dict) → одна строка на уникальный лист.

    Из ревизий одного листа остаётся последняя (MAX(status_date),
    при равенстве — MAX(id)). Результат упорядочен по id.
    Строки с пустым sheet_number не склеиваются (fallback по id).

    Аннулирование «липкое» (патч 12): если хотя бы одна ревизия листа
    имеет статус «Аннулировано», оставленной строке присваивается
    статус 'АННУЛИРОВАНО' — даже когда последняя ревизия живая.
    Без этого аннулированная ревизия проигрывала последней живой
    по (status_date, id) и лист «переставал быть аннулированным»:
    в Сводке «Аннулировано» падало в 0 вместо реальных значений.

    Патч 13: у оставленных строк нормализуется complex (_norm_complex):
    группировки дальше по сырым значениям (разрез «По комплектам»
    в Сводке, GROUP BY в Плане выдачи) больше не делят комплект
    между вариантами написания шифра (латиница/пробелы).
    Входные dict'ы не мутируются.
    """
    best: dict[tuple, dict] = {}
    annulled_keys: set[tuple] = set()
    for r in rows or []:
        if not isinstance(r, dict):
            continue
        key = sheet_key(r)
        if _s(r.get("status")).upper() == "АННУЛИРОВАНО":
            annulled_keys.add(key)
        cur = best.get(key)
        if cur is None or _rev_order(r) > _rev_order(cur):
            best[key] = r
    for key in annulled_keys:
        row = best.get(key)
        if row is not None and _s(row.get("status")).upper() != "АННУЛИРОВАНО":
            # копия, чтобы не мутировать входные dict'и вызывающего
            row = dict(row)
            row["status"] = "АННУЛИРОВАНО"
            best[key] = row
    kept = []
    for r in best.values():
        raw_cx = r.get("complex")
        cx_norm = _norm_complex(raw_cx)
        # копия — если сырое значение отличается от нормализованного
        # (пробелы, регистр, латиница); входные dict'ы не мутируем
        if cx_norm and (raw_cx is None or str(raw_cx) != cx_norm):
            r = dict(r)
            r["complex"] = cx_norm
        kept.append(r)
    return sorted(kept, key=lambda r: _int(r.get("id")))


def dedup_documents(df):
    """
    pandas-обёртка dedup_document_rows: DataFrame documents → DataFrame
    уникальных листов. Колонки и их порядок сохраняются. Если колонки
    sheet_number нет — DataFrame возвращается без изменений.
    """
    import pandas as pd

    if df is None or len(df) == 0 or "sheet_number" not in df.columns:
        return df
    kept = dedup_document_rows(df.to_dict("records"))
    if not kept:
        return df.iloc[0:0]
    return pd.DataFrame(kept).reindex(columns=df.columns)


# ---------------------------------------------------------------------------
#  SQL-выражение для подсчёта в запросах
# ---------------------------------------------------------------------------
def sql_count_sheets(alias: str = "d") -> str:
    """
    SQL-выражение: число УНИКАЛЬНЫХ листов в группе (стандарт патча 11).

    Вставляется в запрос вместо COUNT(DISTINCT {alias}.id) / COUNT(*).
    Ключ — (complex, sheet_number); строки с пустым sheet_number
    считаются поодиночке (по id). COALESCE(complex,'') защищает от
    потери строк с NULL-комплектом (NULL || x = NULL в SQLite).

    Патч 13: перед TRIM табуляция (CHAR 9) и неразрывный пробел
    (CHAR 160) заменяются обычным пробелом — иначе SQL TRIM (он
    снимает только пробел 0x20) расходился с pandas-дедупликацией
    (_s снимает \xa0): номер «10\xa0» в SQL считался отдельным листом,
    а в Сводке приклеивался к «10».
    """
    a = alias
    return (
        f"COUNT(DISTINCT CASE "
        f"WHEN TRIM(REPLACE(REPLACE(COALESCE({a}.sheet_number, ''), "
        f"CHAR(9), ' '), CHAR(160), ' ')) != '' "
        f"THEN TRIM(REPLACE(REPLACE(COALESCE({a}.complex, ''), "
        f"CHAR(9), ' '), CHAR(160), ' ')) || '||' "
        f"|| TRIM(REPLACE(REPLACE({a}.sheet_number, "
        f"CHAR(9), ' '), CHAR(160), ' ')) "
        f"ELSE 'row:' || {a}.id END)"
    )


# ---------------------------------------------------------------------------
#  Статус комплекта по листам Витро (патч 21)
# ---------------------------------------------------------------------------
# Статус комплекта — сводка по статусам его УНИКАЛЬНЫХ листов
# (unique_vitro_sheets: последние ревизии, «липкое» аннулирование,
# нормализация шифров). Используется подвкладкой «🔄 Обновить статусы»
# вкладки «Экспорт» (vitro/ui/export.py) для внешних перечней
# комплектов Excel.
#
# Правила (ТЗ патча 21, согласованы):
#   1. Листы комплекта берутся из БД по последним ревизиям.
#   2. Листов нет → «План (не загружен)».
#   3. Статусы нормализуются (strip, верхний регистр).
#   4. «И» и «АННУЛИРОВАНО» игнорируются.
#   5. После игнора пусто → «План (не загружен)».
#   6. Все статусы == «A» → «A».
#   7. Все статусы в {A, B} и есть хотя бы один «B» → «B».
#   8. Иначе → «C»: есть «C», служебные статусы («ДЛЯ СОГЛАСОВАНИЯ»,
#      «НА РАССМОТРЕНИИ», «НА КОРРЕКТИРОВКЕ», «РАЗМЕЩЕНО») или
#      неизвестный статус — комплект в работе.
# Статусы A/B/C сравниваются с ЛАТИНСКИМИ буквами — тот же стандарт,
# что во всех вкладках (plan.py, export.py, Сводка).
KIT_STATUS_NOT_LOADED = "План (не загружен)"

# Статусы, НЕ влияющие на статус комплекта (правило 4):
# «И» — информационный лист, «АННУЛИРОВАНО» — лист выведен из состава.
_KIT_IGNORED_STATUSES = ("И", "АННУЛИРОВАНО")


def normalize_kit_code(code) -> str:
    """Каноническая форма шифра комплекта (патч 21): trim (включая
    неразрывный пробел \xa0), верхний регистр, латинские двойники →
    кириллица. None/NaN → ''.

    Публичная обёртка _norm_complex: шифры из внешних Excel-перечней
    («Обновить статусы», export.py) сопоставляются с базой именно
    через эту функцию — один комплект, написанный латиницей и
    кириллицей, даёт один ключ (тот же стандарт, что в дедупликации).
    """
    return _norm_complex(code)


def _kit_status_from_statuses(statuses) -> str:
    """Чистое ядро правил патча 21 (без обращения к БД).

    statuses — любые статусы листов комплекта (сырые из documents:
    «A», «b », «И», «Аннулировано», «ДЛЯ СОГЛАСОВАНИЯ»…). Каждый
    нормализуется (strip, nbsp → пробел, верхний регистр), «И» и
    «АННУЛИРОВАНО» игнорируются, по оставшимся уникальным значениям
    возвращается статус комплекта (см. правила в шапке секции).
    Пустой вход / всё проигнорировано → «План (не загружен)».

    Согласованное дополнение: статусы, не входящие в A/B/C/И/
    АННУЛИРОВАНО и служебные, трактуются как «C» (комплект в работе).
    """
    uniq = set()
    for s in (statuses or []):
        v = _s(s).replace("\xa0", " ").upper()
        if v:
            uniq.add(v)
    uniq -= set(_KIT_IGNORED_STATUSES)
    if not uniq:
        return KIT_STATUS_NOT_LOADED
    if uniq == {"A"}:
        return "A"
    if uniq <= {"A", "B"}:
        # Подмножество {A, B}, не равное {A} — значит, есть хотя бы один B
        return "B"
    return "C"


def _load_vitro_sheets_raw() -> list:
    """Строки documents (dict) для расчёта статусов комплектов.

    Тот же срез, что в _vitro_sheet_counts «Плана выдачи» (plan.py):
    id, complex, sheet_number, status, status_date по всем строкам
    с непустым complex. Дедупликация — на стороне unique_vitro_sheets,
    БД не изменяется.

    get_conn импортируется ВНУТРИ функции: sqlite_db импортирует
    sheets на уровне модуля (vitro/sqlite_db.py), прямой импорт в
    шапке sheets.py дал бы цикл.
    """
    from vitro.sqlite_db import get_conn

    with get_conn() as conn:
        rows = conn.execute(
            "SELECT id, complex, sheet_number, status, status_date "
            "FROM documents "
            "WHERE complex IS NOT NULL"
        ).fetchall()
    return [dict(r) for r in rows]


def get_kit_status(complex_code: str) -> str:
    """Статус комплекта по последним ревизиям его листов (патч 21).

    Возвращает «A», «B», «C» или «План (не загружен)» — правила в
    шапке секции. Листы комплекта = unique_vitro_sheets (дедуп
    ревизий, «липкое» аннулирование, нормализация шифров, отсечение
    мусорных), отфильтрованные по каноническому шифру.

    Одиночный вызов делает полный срез documents (как все вкладки):
    для перечней из Excel использовать батчевый get_kit_statuses —
    один проход БД на весь список шифров.
    """
    code = normalize_kit_code(complex_code)
    if not code:
        return KIT_STATUS_NOT_LOADED
    kit_sheets = [
        r for r in unique_vitro_sheets(_load_vitro_sheets_raw())
        if str(r.get("complex") or "") == code
    ]
    return _kit_status_from_statuses(
        r.get("status") for r in kit_sheets)


def get_kit_statuses(codes=None) -> dict:
    """Батчевый вариант get_kit_status (патч 21): ОДИН проход по БД
    на весь список шифров.

    codes=None → статусы всех комплектов базы ({шифр: статус}).
    Иначе — список/кортеж шифров (строка трактуется как один шифр):
    шифры нормализуются, отсутствующие в Витро → «План (не загружен)»,
    пустые шифры в результат не включаются. Ключи результата —
    канонические шифры (normalize_kit_code), значения — «A» / «B» /
    «C» / «План (не загружен)» — ровно то, что вернул бы
    get_kit_status для каждого шифра (общее ядро правил).
    """
    statuses_by_kit: dict = {}
    for r in unique_vitro_sheets(_load_vitro_sheets_raw()):
        cx = str(r.get("complex") or "")
        if not cx:
            continue
        statuses_by_kit.setdefault(cx, []).append(r.get("status"))

    result = {
        cx: _kit_status_from_statuses(sts)
        for cx, sts in statuses_by_kit.items()
    }

    if codes is None:
        return result

    if isinstance(codes, str):
        codes = [codes]
    out: dict = {}
    for c in codes or []:
        key = normalize_kit_code(c)
        if not key:
            continue  # пустой шифр — не комплект; UI подставит дефолт
        out[key] = result.get(key, KIT_STATUS_NOT_LOADED)
    return out

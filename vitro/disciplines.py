"""
Справочник дисциплин. Взят из структуры Витро (/01_РД/02_АТП/01_В процессе/).
"""

DISCIPLINE_NAMES: dict[str, str] = {
    "01_АР":   "Архитектурные решения",
    "01_АС":   "Архитектурно-строительные решения",
    "02_КР":   "Конструктивные решения",
    "03_ЭС":   "Электрические системы",
    "04_МЕХ":  "Механические системы",
    "05_ТХ":   "Технологические решения и оборудование",
    "06_ВТ":   "Вертикальный транспорт",
    "06_ГК":   "Газовая котельная",
    "06_ДГУ":  "Дизель-генераторная установка",
    "06_ХЦ":   "Холодильный центр",
    "07_ГП,АД": "Генеральный план, УДС",
}


def discipline_name(code: str) -> str:
    """Возвращает полное название дисциплины по коду."""
    return DISCIPLINE_NAMES.get(code, code)